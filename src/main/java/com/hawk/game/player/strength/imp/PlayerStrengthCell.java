package com.hawk.game.player.strength.imp;

public class PlayerStrengthCell {
	
	/**
	 * 攻击加成
	 */
	private int atk;
	
	/**
	 * 血量加成
	 */
	private int hp;
	
	/**
	 * 星穹护盾值
	 */
	private int shd;

	public int getAtk() {
		return atk;
	}

	public void setAtk(int atk) {
		this.atk = atk;
	}

	public int getHp() {
		return hp;
	}

	public void setHp(int hp) {
		this.hp = hp;
	}

	public int getShd() {
		return shd;
	}

	public void setShd(int shd) {
		this.shd = shd;
	}
	
}
